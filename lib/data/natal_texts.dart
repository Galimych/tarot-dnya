/// Полный текст аспекта: смысл пары + характер аспекта.
String aspectDescription(String a, String b, String typeName) {
  String theme;
  if (b == 'Асцендент') {
    theme = 'Связь ${planetRole[a] ?? 'планеты'} с тем, как ты проявляешься в мире и каким тебя видят другие.';
  } else if (b.startsWith('Середина неба')) {
    theme = 'Связь ${planetRole[a] ?? 'планеты'} с призванием, карьерой и общественным образом.';
  } else {
    theme = planetPairTheme['$a|$b'] ?? planetPairTheme['$b|$a'] ?? '';
  }
  final line = aspectTypeLine[typeName] ?? '';
  return theme.isEmpty ? line : '$theme $line';
}
